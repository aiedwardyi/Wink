/** True when seen holds any 8-character run of value, or all of a shorter one. */
export function sendsValue(seen: string, value: string): boolean {
  if (value.length < 8) return seen.includes(value);
  for (let at = 0; at + 8 <= value.length; at++) if (seen.includes(value.slice(at, at + 8))) return true;
  return false;
}
